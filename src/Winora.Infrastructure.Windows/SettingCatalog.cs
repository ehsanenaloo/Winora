    public static RegistryValueSpec Text(string value) => new(RegistryDataKind.String, Encoding.Unicode.GetBytes(value));

    private static SettingChoice C(string id, string choice, RegistryValueSpec value) =>
        new(choice, "Choice_" + id.Replace('.', '_') + "_" + choice, value);

    private static SettingDefinition D(string id, SettingCategory category, RecoveryKind recovery, bool explorer, bool signOut, int? min, int? max,
        string subKey, string valueName, string defaultChoice, string? recommended, string source, params SettingChoice[] choices)
    {
        var key = id.Replace('.', '_');
        return new(id, 1, $"Setting_{key}_Title", $"Setting_{key}_Description", category, RiskLevel.Low, recovery, explorer, signOut, min, max,
            new RegistryTarget(subKey, valueName), choices, defaultChoice, recommended, source);
    }

    private static RegistryTarget T(string subKey, string valueName) => new(subKey, valueName);

    private static RegistryTarget TKey(string subKey, RegistryKeyMode mode) => new(subKey, "") { Mode = mode };

    /// <summary>A choice of a grouped (or single) row: one spec per member, in member order.</summary>
    private static SettingChoice Ch(string id, string choice, params RegistryValueSpec[] values) =>
        new(choice, "Choice_" + id.Replace('.', '_') + "_" + choice, RegistryValueSpec.Group(values));

    private static SettingDefinition G(string id, SettingCategory category, RiskLevel risk, RecoveryKind recovery, bool explorer, bool signOut, int? min, int? max,
        RegistryTarget[] targets, string defaultChoice, string? recommended, string source, params SettingChoice[] choices)
    {
        var key = id.Replace('.', '_');
        return new(id, 1, $"Setting_{key}_Title", $"Setting_{key}_Description", category, risk, recovery, explorer, signOut, min, max,
            targets[0], choices, defaultChoice, recommended, source) { ExtraTargets = targets[1..] };
    }

